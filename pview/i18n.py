TABLES = {"zh": _ZH, "en": _EN}


def set_language(lang: str):
    global CURRENT
    CURRENT = lang if lang in TABLES else "en"


def tr(key: str, *args) -> str:
    s = TABLES.get(CURRENT, _EN).get(key)
    if s is None:
        s = _EN.get(key, key)
    if args:
        try:
            return s.format(*args)
        except Exception:
            return s
    return s
